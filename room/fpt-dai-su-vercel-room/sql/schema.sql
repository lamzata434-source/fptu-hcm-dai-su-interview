CREATE TABLE IF NOT EXISTS slots (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  env text NOT NULL CHECK(env IN ('test','live')),
  committee_id integer NOT NULL REFERENCES committees(id),
  start_at timestamptz NOT NULL,
  room text NOT NULL DEFAULT '',
  capacity integer NOT NULL DEFAULT 6 CHECK(capacity BETWEEN 1 AND 200),
  open boolean NOT NULL DEFAULT true,
  UNIQUE(env,committee_id,start_at)
);
CREATE INDEX IF NOT EXISTS slots_env_time ON slots(env,start_at);

CREATE TABLE IF NOT EXISTS registrations (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  env text NOT NULL CHECK(env IN ('test','live')),
  committee_id integer NOT NULL REFERENCES committees(id),
  slot_id bigint NOT NULL REFERENCES slots(id) ON DELETE RESTRICT,
  student_name text NOT NULL,
  student_id text NOT NULL,
  lookup_hash text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(env,committee_id,student_id)
);
CREATE INDEX IF NOT EXISTS registrations_env_student ON registrations(env,student_id);
CREATE INDEX IF NOT EXISTS registrations_slot_id ON registrations(slot_id);

CREATE TABLE IF NOT EXISTS auth_attempts (
  ip_hash text PRIMARY KEY,
  attempts integer NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS admin_audit (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  action text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

